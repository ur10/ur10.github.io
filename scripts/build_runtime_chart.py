"""Build the inline SVG runtime chart for projects/certifiable-imu/ from assets/imu/scaling.csv.

Single-thread rows only; the plotted value is the median over the recorded start windows.
Writes projects/certifiable-imu/runtime-chart.html (an HTML fragment) and splices it into the
page between the RUNTIME-CHART markers. Run from the repository root: python3 scripts/build_runtime_chart.py
"""
import csv, math, statistics, re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
rows = [r for r in csv.DictReader(open(root / 'assets/imu/scaling.csv')) if r['threads'] == '1' and r['status'] == 'ok']
SERIES = [('mosek (published)', 'Dense MOSEK', 's1'), ('mosek + presolve', 'Dense + presolve', 's2'), ('mosek_chordal', 'Chordal MOSEK', 's3')]
data = {}
for cfg, _, _ in SERIES:
    g = {}
    for r in rows:
        if r['config'] == cfg:
            g.setdefault(float(r['T']), []).append(float(r['wall']))
    data[cfg] = {T: sorted(v) for T, v in sorted(g.items())}

W, H = 720, 330
L, R, T, B = 58, 600, 14, 280
X0, X1 = math.log2(4), math.log2(64)
Y0, Y1 = math.log10(0.3), math.log10(150)
X = lambda t: L + (math.log2(t) - X0) / (X1 - X0) * (R - L)
Y = lambda s: B - (math.log10(s) - Y0) / (Y1 - Y0) * (B - T)
f = lambda v: f'{v:.1f}'
def fmt(s): return f'{s:.2f} s' if s < 10 else f'{s:.1f} s'

out = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-labelledby="rt-title rt-desc">',
       '<title id="rt-title">Solve time versus estimation window length</title>',
       '<desc id="rt-desc">Log-log chart. Dense MOSEK and dense with presolve grow from about 0.5 s at a 4 s window to about 75 to 81 s at 32 s. The chordal decomposition grows from 0.5 s to 6.1 s at 32 s and 16.3 s at 64 s.</desc>']
for s, lab in [(1, '1 s'), (10, '10 s'), (100, '100 s')]:
    out.append(f'<line class="c-grid" x1="{L}" x2="{R}" y1="{f(Y(s))}" y2="{f(Y(s))}"/>')
    out.append(f'<text class="c-tick" x="{L-8}" y="{f(Y(s)+4)}" text-anchor="end">{lab}</text>')
out.append(f'<line class="c-axis" x1="{L}" x2="{R}" y1="{B}" y2="{B}"/>')
for t in [4, 8, 16, 32, 64]:
    out.append(f'<text class="c-tick" x="{f(X(t))}" y="{B+18}" text-anchor="middle">{t} s</text>')
out.append(f'<text class="c-lab" x="{(L+R)/2}" y="{H-4}" text-anchor="middle">Estimation window length (log scale)</text>')
out.append(f'<text class="c-lab" transform="translate(14 {(T+B)/2}) rotate(-90)" text-anchor="middle">Wall-clock time, one thread</text>')
labels = {'mosek (published)': -10, 'mosek + presolve': 16, 'mosek_chordal': 4}
for cfg, name, var in SERIES:
    pts = [(T_, statistics.median(v), v) for T_, v in data[cfg].items()]
    for T_, _, v in pts:
        for w in v:
            out.append(f'<circle class="c-run" cx="{f(X(T_))}" cy="{f(Y(w))}" r="3" fill="var(--{var})"/>')
    d = ' '.join(('M' if i == 0 else 'L') + f'{f(X(t))} {f(Y(m))}' for i, (t, m, _) in enumerate(pts))
    out.append(f'<path class="c-line" d="{d}" stroke="var(--{var})"/>')
    for t, m, v in pts:
        out.append(f'<circle class="c-pt" cx="{f(X(t))}" cy="{f(Y(m))}" r="4.5" fill="var(--{var})"/>')
        tip = f'{name} · {t:g} s window · median {fmt(m)} ({len(v)} runs: {", ".join(fmt(w) for w in v)})'
        out.append(f'<circle class="c-hit" cx="{f(X(t))}" cy="{f(Y(m))}" r="13" tabindex="0" data-tip="{tip}" aria-label="{tip}"/>')
    t, m, _ = pts[-1]
    out.append(f'<text class="c-dl" x="{f(X(t)+12)}" y="{f(Y(m)+labels[cfg])}">{name}</text>')
out.append('</svg>')
svg = '\n'.join(out)

head = ''.join(f'<li><i style="background:var(--{v})"></i>{n}</li>' for _, n, v in SERIES)
trs = []
for t in [4, 8, 16, 32, 64]:
    cells = []
    for cfg, _, _ in SERIES:
        v = data[cfg].get(float(t))
        cells.append(f'<td class="r">{fmt(statistics.median(v))}</td>' if v else '<td class="r">not run</td>')
    trs.append(f'<tr><th scope="row">{t} s</th>{"".join(cells)}</tr>')
frag = f'''<!-- RUNTIME-CHART:START (generated by scripts/build_runtime_chart.py) -->
<figure class="chart" style="margin:0">
  <p class="chart-title">Solve time grows with the window; chordal decomposition flattens it</p>
  <p class="chart-sub">Median over recorded start windows; faint points are individual runs. Hover a point for values.</p>
  <ul class="legend">{head}</ul>
  {svg}
  <details class="data-view"><summary>Show as a table</summary>
    <div class="table-wrap"><table class="data"><thead><tr><th scope="col">Window</th>{"".join(f'<th scope="col" class="r">{n}</th>' for _, n, _ in SERIES)}</tr></thead><tbody>{"".join(trs)}</tbody></table></div>
  </details>
</figure>
<!-- RUNTIME-CHART:END -->'''
page = root / 'projects/certifiable-imu/index.html'
if page.exists():
    s = page.read_text()
    s2 = re.sub(r'<!-- RUNTIME-CHART:START.*?RUNTIME-CHART:END -->', lambda m: frag, s, flags=re.S)
    page.write_text(s2)
    print('spliced into', page, 'changed' if s2 != s else 'unchanged')
else:
    print(frag)
